import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { analyzeRhinoStatic } from "./lib/messengerbot-rhino-static.mjs";

const require = createRequire(import.meta.url);
const acorn = require("next/dist/compiled/acorn");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const directory = resolve(root, "integrations/messengerbot-r/v4");
const shared = (await readFile(resolve(directory, "KLOL_KAKAO_BOT_V4_SHARED.js"), "utf8")).replace(/\r\n?/gu, "\n").trim();
const sourceName = "KLOL_KAKAO_BOT_V4_UNIFIED.js";
const outputName = "KLOL_KAKAO_BOT_V4_UNIFIED_MESSENGERBOT_R.js";
const entry = (await readFile(resolve(directory, sourceName), "utf8")).replace(/\r\n?/gu, "\n").trim();
const output = `/* GENERATED by scripts/build-messengerbot-v4.mjs. Edit SHARED or ${sourceName}. */\n${shared}\n\n${entry}\n`;
const program = acorn.parse(output, { ecmaVersion: 5, allowReserved: true, preserveParens: true });
const findings = analyzeRhinoStatic(program);

if ((output.match(/function\s+response\s*\(/gu) ?? []).length !== 1) throw new Error("UNIFIED output must define one response callback");
if (output.length >= 40_000) throw new Error("UNIFIED output exceeds the 40,000 character release budget");
if (Math.max(...output.split("\n").map((line) => line.length)) > 1_000) throw new Error("UNIFIED output contains an unreadably long line");
if (findings.statementCandidates.length || findings.unsafeSequenceOperands.length || findings.voidExpressions.length || findings.bareAssignmentConditions.length) {
  throw new Error("UNIFIED output contains Rhino static warning candidates");
}
await writeFile(resolve(directory, outputName), output, "utf8");
console.log(`Generated integrations/messengerbot-r/v4/${outputName} (${output.length} characters)`);

for (const legacySourceName of ["KLOL_KAKAO_BOT_V4_RECRUIT.js", "KLOL_KAKAO_BOT_V4_FEATURES.js"]) {
  const legacyEntry = (await readFile(resolve(directory, legacySourceName), "utf8")).replace(/\r\n?/gu, "\n").trim();
  const legacyOutputName = legacySourceName.replace(/\.js$/u, "_MESSENGERBOT_R.js");
  const legacyOutput = `/* GENERATED by scripts/build-messengerbot-v4.mjs. Edit SHARED or ${legacySourceName}. */\n${shared}\n\n${legacyEntry}\n`;
  const legacyProgram = acorn.parse(legacyOutput, { ecmaVersion: 5, allowReserved: true, preserveParens: true });
  const legacyFindings = analyzeRhinoStatic(legacyProgram);
  if ((legacyOutput.match(/function\s+response\s*\(/gu) ?? []).length !== 1) throw new Error(`${legacySourceName} output must define one response callback`);
  if (legacyOutput.length >= 40_000) throw new Error(`${legacySourceName} output exceeds the 40,000 character release budget`);
  if (Math.max(...legacyOutput.split("\n").map((line) => line.length)) > 1_000) throw new Error(`${legacySourceName} output contains an unreadably long line`);
  if (legacyFindings.statementCandidates.length || legacyFindings.unsafeSequenceOperands.length || legacyFindings.voidExpressions.length || legacyFindings.bareAssignmentConditions.length) {
    throw new Error(`${legacySourceName} output contains Rhino static warning candidates`);
  }
  await writeFile(resolve(directory, "legacy-split-profiles", legacyOutputName), legacyOutput, "utf8");
  console.log(`Generated integrations/messengerbot-r/v4/legacy-split-profiles/${legacyOutputName} (${legacyOutput.length} characters)`);
}
