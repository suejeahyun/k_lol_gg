import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const acorn = require("next/dist/compiled/acorn");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const directory = resolve(root, "integrations/messengerbot-r/v4");
const shared = (await readFile(resolve(directory, "KLOL_KAKAO_BOT_V4_SHARED.js"), "utf8")).replace(/\r\n?/gu, "\n").trim();

for (const profile of ["RECRUIT", "FEATURES"]) {
  const sourceName = `KLOL_KAKAO_BOT_V4_${profile}.js`;
  const outputName = `KLOL_KAKAO_BOT_V4_${profile}_MESSENGERBOT_R.js`;
  const entry = (await readFile(resolve(directory, sourceName), "utf8")).replace(/\r\n?/gu, "\n").trim();
  const output = `/* GENERATED by scripts/build-messengerbot-v4.mjs. Edit SHARED or ${sourceName}. */\n${shared}\n\n${entry}\n`;
  acorn.parse(output, { ecmaVersion: 5, allowReserved: true });
  if ((output.match(/function\s+response\s*\(/gu) ?? []).length !== 1) throw new Error(`${profile} output must define one response callback`);
  if (output.length >= 65_535) throw new Error(`${profile} output exceeds the MessengerBot R editor limit`);
  await writeFile(resolve(directory, outputName), output, "utf8");
  console.log(`Generated integrations/messengerbot-r/v4/${outputName} (${output.length} characters)`);
}
