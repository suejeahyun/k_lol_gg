import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { minify } = require("next/dist/compiled/terser");
const acorn = require("next/dist/compiled/acorn");

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const integrationDirectory = resolve(root, "integrations/messengerbot-r");
const transportPath = resolve(integrationDirectory, "KLOL_KAKAO_BOT_V41_V2_TRANSPORT.js");
const compatibilityPath = resolve(integrationDirectory, "KLOL_KAKAO_BOT_V41_V1_COMPAT.js");
const routerPath = resolve(integrationDirectory, "KLOL_KAKAO_BOT_V41_V2_ROUTER.js");
const outputPath = resolve(integrationDirectory, "KLOL_KAKAO_BOT_V41_V2_COMPLETE.js");
const mobileOutputPath = resolve(integrationDirectory, "KLOL_KAKAO_BOT_V41_MESSENGERBOT_R.js");
const bundleMarker = "KLOL_V41_BUNDLE_R11_ROOM_CALLBACK_TRACE";

const [transportSource, compatibilitySource, routerSource] = await Promise.all([
  readFile(transportPath, "utf8"),
  readFile(compatibilityPath, "utf8"),
  readFile(routerPath, "utf8"),
]);

const normalizeLf = (source) => source.replace(/\r\n?/g, "\n");
const transport = normalizeLf(transportSource);
const compatibility = normalizeLf(compatibilitySource);
const router = normalizeLf(routerSource);

const banner = "/* GENERATED by scripts/build-messengerbot-v41.mjs. Edit TRANSPORT, V1_COMPAT, or ROUTER, then rebuild. */\n";
const startSentinel = `var KLOL_V41_BUNDLE_START_SENTINEL = "${bundleMarker}_START";\n`;
const endSentinel = `var KLOL_V41_BUNDLE_END_SENTINEL = "${bundleMarker}_END";\n`;
const complete = `${banner}${startSentinel}${transport.trim()}\n\n${compatibility.trim()}\n\n${router.trim()}\n${endSentinel}`;
const mobileAst = await minify(complete, {
  ecma: 5,
  compress: {
    defaults: false,
    dead_code: true,
    unused: true,
    booleans: true,
    collapse_vars: false,
    comparisons: true,
    conditionals: false,
    evaluate: true,
    if_return: false,
    join_vars: false,
    loops: false,
    reduce_vars: false,
    sequences: false,
    side_effects: false,
    top_retain: ["response"],
    toplevel: true,
    passes: 2,
  },
  mangle: { toplevel: true, reserved: ["response"] },
  keep_fnames: /^response$/u,
  format: {
    ascii_only: false,
    comments: false,
    ecma: 5,
    beautify: true,
    semicolons: true,
  },
});

if (!mobileAst.code) throw new Error("MessengerBot R mobile bundle generation failed");

function compactPreservingSemicolons(source) {
  const tokenizer = acorn.tokenizer(source, { ecmaVersion: 5, allowReserved: true });
  const tokens = [];
  while (true) {
    const token = tokenizer.getToken();
    if (token.type.label === "eof") break;
    tokens.push({ raw: source.slice(token.start, token.end), type: token.type.label });
  }
  let output = "";
  let previous = null;
  let closingBraceCount = 0;
  let semicolonCount = 0;
  for (const token of tokens) {
    const priorLast = previous?.raw.slice(-1) ?? "";
    const currentFirst = token.raw.charAt(0);
    const wordsTouch = /[A-Za-z0-9_$]/u.test(priorLast) && /[A-Za-z0-9_$]/u.test(currentFirst);
    const operatorsTouch = (priorLast === "+" && currentFirst === "+") ||
      (priorLast === "-" && currentFirst === "-") ||
      (priorLast === "/" && currentFirst === "/");
    const keywordBeforeRegex = token.type === "regexp" && /^(?:return|throw|case|delete|void|typeof|new|in|instanceof)$/u.test(previous?.raw ?? "");
    if (wordsTouch || operatorsTouch || keywordBeforeRegex) output += " ";
    output += token.raw;
    if (token.raw === ";") {
      semicolonCount += 1;
      if (semicolonCount % 8 === 0) output += "\n";
    }
    if (token.raw === "}") {
      closingBraceCount += 1;
      if (closingBraceCount % 8 === 0) output += "\n";
    }
    previous = token;
  }
  return output;
}

const mobile = compactPreservingSemicolons(mobileAst.code);
if (mobile.length >= 65_535) {
  throw new Error(`MessengerBot R mobile bundle exceeds the 65,535 character limit: ${mobile.length}`);
}
const projectedCrLfLength = mobile.length + (mobile.match(/\n/g) ?? []).length;
if (projectedCrLfLength >= 65_535) {
  throw new Error(`MessengerBot R mobile bundle exceeds the 65,535 character limit after CRLF conversion: ${projectedCrLfLength}`);
}

await Promise.all([
  writeFile(outputPath, complete, "utf8"),
  writeFile(mobileOutputPath, mobile, "utf8"),
]);
console.log("Generated integrations/messengerbot-r/KLOL_KAKAO_BOT_V41_V2_COMPLETE.js");
console.log("Generated integrations/messengerbot-r/KLOL_KAKAO_BOT_V41_MESSENGERBOT_R.js");
console.log(`MessengerBot R mobile characters: ${mobile.length}`);
console.log(`MessengerBot R mobile CRLF projection: ${projectedCrLfLength}`);
